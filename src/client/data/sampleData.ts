export function sampleCIDetail(sysId: string): CIDetail | null {
  const node = nodes.find((n) => n.id === sysId);
  if (!node) return null;
  return {
    id: node.id,
    name: node.name,
    class: node.class,
    operational_status: node.operational_status,
    install_status: "Installed",
    health: node.health,
    incident_count: node.incident_count,
    open_incidents: sampleIncidents[node.id] || [],
  };
}
